        assert_eq!(next["schemaVersion"], 1);

        let pet = &next["pets"][0];
        assert_eq!(pet["id"], "pet-1");
        assert_eq!(pet["name"], "Rex");
        assert_eq!(pet["assetId"], "cato");
        assert_eq!(pet["profileId"], "profile-1");
        assert_eq!(pet["workingDirectoryId"], "dir-1");
