//! The pure aggregate mutations: given the current document, an already-typed
//! input, freshly allocated ids, and a timestamp, produce the next document or
//! a typed error. These functions never touch a clock, an id source, or the
//! repository, so they stay deterministic and directly testable — the facade in
//! [`crate::lib`] wires them to the transaction.

use serde_json::Value;

use crate::error::{CoreError, ValidationError};
use crate::model::{HatchPet, Patch, PetId, PetPatch, SettingsPatch};
use crate::personalities::personality_preset;
use crate::queries::find_pet_id_by_cwd;
use crate::state_v1::{empty_state, push_array, PET_DATA_KEYS};
use crate::working_directory::{comparable_path, is_valid_working_directory};
use crate::{asset_id, WorkingDirectoryPath};

/// The ids a Pet Birth needs, generated by the caller so [`apply_hatch`] stays
/// pure.
pub(crate) struct HatchIds {
    pub pet_id: String,
    pub profile_id: String,
    pub working_directory_id: String,
    pub agent_source_id: String,
}

/// The ids a working-directory re-bind needs (mirrors [`HatchIds`]).
pub(crate) struct WorkingDirectoryIds {
    pub working_directory_id: String,
    pub agent_source_id: String,
}

/// Pet Birth: create the Pet and its Pet Profile atomically, plus a Registered
/// Working Directory when a folder was supplied. Rejects an unknown
/// personality, an unusable folder path, and a folder already held by another
/// pet — leaving the document unchanged in every rejection.
pub(crate) fn apply_hatch(
    state: &Value,
    input: &HatchPet,
    ids: &HatchIds,
    now: u64,
) -> Result<Value, CoreError> {
    let personality = personality_preset(&input.personality_id)
        .ok_or(ValidationError::UnknownPersonality)?;

    if let Some(cwd) = &input.working_directory {
        if !is_valid_working_directory(cwd.as_str()) {
            return Err(ValidationError::InvalidWorkingDirectory.into());
        }

        if let Some(owner_pet_id) = occupant_of(state, cwd) {
            return Err(CoreError::WorkingDirectoryOccupied { owner_pet_id });
        }
    }

    let mut next = state.clone();

    push_array(
        &mut next,
        "pets",
        serde_json::json!({
            "id": ids.pet_id,
            "workingDirectoryId": input.working_directory.as_ref().map(|_| ids.working_directory_id.clone()),
            "assetId": input.asset_id,
            "profileId": ids.profile_id,
            "name": input.name,
            "adoptedAt": now,
            "archived": false,
            "visible": true
        }),
    );
    push_array(
        &mut next,
        "petProfiles",
        serde_json::json!({
            "id": ids.profile_id,
            "petAssetId": input.asset_id,
            "personalityId": input.personality_id,
            "personality": personality
        }),
    );
    // A pet can be adopted with no folder bound: it lives on and receives no
    // agent events until one is picked from its settings.
    if let Some(cwd) = &input.working_directory {
        push_array(
            &mut next,
            "registeredWorkingDirectories",
            serde_json::json!({
                "id": ids.working_directory_id,
                "path": cwd.as_str(),
                "petId": ids.pet_id,
                "agentSourceId": ids.agent_source_id,
                "createdAt": now,
                "updatedAt": now
            }),
        );
    }

    Ok(next)
}

/// The pet id that already holds `cwd`, comparing folders case- and
/// separator-insensitively.
fn occupant_of(state: &Value, cwd: &WorkingDirectoryPath) -> Option<String> {
    let target = cwd.comparable();
    state
        .get("registeredWorkingDirectories")
        .and_then(|value| value.as_array())?
        .iter()
        .find(|directory| {
            directory
                .get("path")
                .and_then(|value| value.as_str())
                .map(|path| comparable_path(path) == target)
                .unwrap_or(false)
        })
        .map(|directory| {
            directory
                .get("petId")
                .and_then(|value| value.as_str())
                .unwrap_or_default()
                .to_string()
        })
}

/// Apply a partial patch to one pet record (and its profile's personality and
/// mirrored asset id, when set). Unset fields are left untouched; a rejected
/// re-bind leaves the other patched fields unwritten too.
pub(crate) fn apply_pet_update(
    state: &Value,
    pet_id: &PetId,
    patch: &PetPatch,
    ids: &WorkingDirectoryIds,
    now: u64,
) -> Result<Value, CoreError> {
    let pet_exists = state
        .get("pets")
        .and_then(|value| value.as_array())
        .is_some_and(|pets| {
            pets.iter()
                .any(|pet| pet.get("id").and_then(|value| value.as_str()) == Some(pet_id.as_str()))
        });

    if !pet_exists {
        return Err(CoreError::PetNotFound {
            pet_id: pet_id.as_str().to_string(),
        });
    }

    let personality = match &patch.personality_id {
        Some(personality_id) => match personality_preset(personality_id) {
            Some(personality) => Some(personality),
            None => return Err(ValidationError::UnknownPersonality.into()),
        },
        None => None,
    };

    // The asset id is addressed as a directory name by the sprite loader and as
    // a query parameter by the pet overlay window, so reject anything those two
    // could not resolve before it reaches disk (same guard as hatching).
    if let Some(asset_id) = &patch.asset_id {
        if !asset_id::is_valid_asset_id(asset_id) {
            return Err(ValidationError::InvalidAssetId.into());
        }
    }

    // Validate the requested folder before touching state, so a rejected
    // re-bind leaves the other patched fields unwritten too.
    if let Patch::Set(cwd) = &patch.working_directory {
        if !is_valid_working_directory(cwd.as_str()) {
            return Err(ValidationError::InvalidWorkingDirectory.into());
        }

        if let Some(owner_pet_id) = find_pet_id_by_cwd(state, cwd.as_str()) {
            if owner_pet_id != pet_id.as_str() {
                return Err(CoreError::WorkingDirectoryOccupied { owner_pet_id });
            }
        }
    }

    let mut next = state.clone();
    let mut profile_id = String::new();

    if let Some(pets) = next.get_mut("pets").and_then(|value| value.as_array_mut()) {
        for pet in pets.iter_mut() {
            if pet.get("id").and_then(|value| value.as_str()) != Some(pet_id.as_str()) {
                continue;
            }

            profile_id = pet
                .get("profileId")
                .and_then(|value| value.as_str())
                .unwrap_or_default()
                .to_string();

            let Some(object) = pet.as_object_mut() else {
                continue;
            };

            if let Some(name) = &patch.name {
                object.insert("name".to_string(), serde_json::json!(name));
            }
            if let Some(asset_id) = &patch.asset_id {
                object.insert("assetId".to_string(), serde_json::json!(asset_id));
            }
            if let Some(visible) = patch.visible {
                object.insert("visible".to_string(), serde_json::json!(visible));
            }
            if let Some(archived) = patch.archived {
                object.insert("archived".to_string(), serde_json::json!(archived));
            }
            if let Some(memo) = &patch.memo {
                object.insert("memo".to_string(), serde_json::json!(memo));
            }
            if let Some(scale) = patch.scale {
                object.insert("scale".to_string(), serde_json::json!(scale));
            }
        }
    }

    // The profile carries both the personality preset and a mirror of the pet's
    // asset id, so patch it once for whichever of the two the caller sent.
    let personality_patch = match (&patch.personality_id, personality) {
        (Some(personality_id), Some(personality)) => Some((personality_id, personality)),
        _ => None,
    };

    if personality_patch.is_some() || patch.asset_id.is_some() {
        if let Some(profiles) = next.get_mut("petProfiles").and_then(|value| value.as_array_mut()) {
            for profile in profiles.iter_mut() {
                if profile.get("id").and_then(|value| value.as_str()) != Some(profile_id.as_str()) {
                    continue;
                }

                let Some(object) = profile.as_object_mut() else {
                    continue;
                };

                if let Some((personality_id, personality)) = &personality_patch {
                    object.insert("personalityId".to_string(), serde_json::json!(personality_id));
                    object.insert("personality".to_string(), (*personality).clone());
                }
                if let Some(asset_id) = &patch.asset_id {
                    object.insert("petAssetId".to_string(), serde_json::json!(asset_id));
                }
            }
        }
    }

    match &patch.working_directory {
        Patch::Keep => {}
        Patch::Clear => apply_pet_working_directory(&mut next, pet_id.as_str(), None, ids, now),
        Patch::Set(cwd) => {
            apply_pet_working_directory(&mut next, pet_id.as_str(), Some(cwd.as_str()), ids, now)
        }
    }

    Ok(next)
}

/// Re-point one pet's registered working directory: `cwd` of `None` detaches
/// it, `Some(path)` binds it to that folder. A pet holds at most one directory
/// and a directory belongs to exactly one pet, so the pet's current entry is
/// dropped either way before a new one is appended, and the pet's back-pointer
/// is kept in step.
fn apply_pet_working_directory(
    next: &mut Value,
    pet_id: &str,
    cwd: Option<&str>,
    ids: &WorkingDirectoryIds,
    now: u64,
) {
    if let Some(directories) = next
        .get_mut("registeredWorkingDirectories")
        .and_then(|value| value.as_array_mut())
    {
        directories
            .retain(|directory| directory.get("petId").and_then(|value| value.as_str()) != Some(pet_id));
    }

    let working_directory_id = match cwd {
        Some(path) => {
            push_array(
                next,
                "registeredWorkingDirectories",
                serde_json::json!({
                    "id": ids.working_directory_id,
                    "path": path,
                    "petId": pet_id,
                    "agentSourceId": ids.agent_source_id,
                    "createdAt": now,
                    "updatedAt": now
                }),
            );
            serde_json::json!(ids.working_directory_id)
        }
        None => Value::Null,
    };

    if let Some(pets) = next.get_mut("pets").and_then(|value| value.as_array_mut()) {
        for pet in pets.iter_mut() {
            if pet.get("id").and_then(|value| value.as_str()) != Some(pet_id) {
                continue;
            }

            if let Some(object) = pet.as_object_mut() {
                object.insert("workingDirectoryId".to_string(), working_directory_id.clone());
            }
        }
    }
}

/// Permanently remove a pet, its profile, and any working directory it holds.
pub(crate) fn apply_remove_pet(state: &Value, pet_id: &PetId) -> Result<Value, CoreError> {
    let pet = state
        .get("pets")
        .and_then(|value| value.as_array())
        .and_then(|pets| {
            pets.iter()
                .find(|pet| pet.get("id").and_then(|value| value.as_str()) == Some(pet_id.as_str()))
        })
        .ok_or_else(|| CoreError::PetNotFound {
            pet_id: pet_id.as_str().to_string(),
        })?;

    let profile_id = pet
        .get("profileId")
        .and_then(|value| value.as_str())
        .unwrap_or_default()
        .to_string();

    let mut next = state.clone();
    let Some(object) = next.as_object_mut() else {
        return Ok(next);
    };

    if let Some(Value::Array(pets)) = object.get_mut("pets") {
        pets.retain(|pet| pet.get("id").and_then(|value| value.as_str()) != Some(pet_id.as_str()));
    }
    if let Some(Value::Array(profiles)) = object.get_mut("petProfiles") {
        profiles.retain(|profile| {
            profile.get("id").and_then(|value| value.as_str()) != Some(profile_id.as_str())
        });
    }
    if let Some(Value::Array(directories)) = object.get_mut("registeredWorkingDirectories") {
        directories
            .retain(|directory| directory.get("petId").and_then(|value| value.as_str()) != Some(pet_id.as_str()));
    }

    Ok(next)
}

/// Patch the app-wide settings, inserting only the fields the caller sent.
pub(crate) fn apply_settings_update(state: &Value, input: &SettingsPatch) -> Value {
    let mut next = state.clone();
    let Some(object) = next.as_object_mut() else {
        return next;
    };

    if let Some(session_command) = &input.session_command {
        object.insert("sessionCommand".to_string(), serde_json::json!(session_command));
    }
    apply_string_patch(object, "terminalShell", &input.terminal_shell);
    apply_string_patch(object, "petSourceDirectory", &input.pet_source_directory);

    next
}

/// Apply one [`Patch<String>`] to a settings object: keep leaves it, set writes
/// the string, clear writes JSON null (which the frontend parser reads as
/// "default").
fn apply_string_patch(
    object: &mut serde_json::Map<String, Value>,
    key: &str,
    patch: &Patch<String>,
) {
    match patch {
        Patch::Keep => {}
        Patch::Set(value) => {
            object.insert(key.to_string(), serde_json::json!(value));
        }
        Patch::Clear => {
            object.insert(key.to_string(), Value::Null);
        }
    }
}

/// Drop every settings key, keeping only the pet data. An absent key is what
/// the frontend parser reads as "default", so removing them is how a setting
/// goes back to its default rather than to an empty string.
pub(crate) fn apply_settings_reset(state: &Value) -> Value {
    let mut next = empty_state();

    let Some(object) = next.as_object_mut() else {
        return next;
    };

    for key in PET_DATA_KEYS {
        if let Some(value) = state.get(key) {
            object.insert(key.to_string(), value.clone());
        }
    }

    next
}

